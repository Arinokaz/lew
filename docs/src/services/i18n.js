let currentLang = "ru";

export function setLang(lang) {
  if (STRINGS[lang]) currentLang = lang;
}

export function getLang() {
  return currentLang;
}

export function t(path, ...args) {
  const parts = path.split(".");
  let cur = STRINGS[currentLang];
  for (const p of parts) {
    if (cur == null) break;
    cur = cur[p];
  }
  if (typeof cur === "function") return cur(...args);
  if (typeof cur === "string" && args.length > 0) {
    if (typeof args[0] === "object" && args[0] !== null) {
      return cur.replace(/\{\{(\w+)\}\}/g, (_, k) => args[0][k] ?? "");
    }
    return cur.replace(/\{\{(\w+)\}\}/g, () => args.shift() ?? "");
  }
  if (cur === undefined) return path;
  return cur;
}

export function availableLangs() {
  return Object.keys(STRINGS);
}
